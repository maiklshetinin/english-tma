// Идентификаторы для новых записей (кружки, юниты, пресеты, колоды, карточки). Их придумывает сайт, а сервер принимает
// любой id из букв, цифр, «_» и «-» (до 40 знаков). Начинаются с буквы, чтобы не путаться с числами в полях форм.
let seq = 0
export const newId = (prefix = 'x'): string => `${prefix}${Date.now().toString(36)}${(++seq).toString(36)}${Math.random().toString(36).slice(2, 6)}`
